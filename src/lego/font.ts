export const FONT_ROWS = 7;

/** Glyph rows top-down; unknown characters fall back to a blank. */
export const glyph = (ch: string) => G[ch.toUpperCase()] ?? G[" "];

/** Width of a word in studs, one stud between letters. */
export function textWidth(text: string) {
  const chars = [...text];
  return chars.reduce((w, ch) => w + glyph(ch)[0].length, 0) + Math.max(0, chars.length - 1);
}
